"""Rules of ci/lock_check.py, on small files shaped like pip-compile's output."""

from __future__ import annotations

from pathlib import Path

import pytest

from lock_check import check, read_lock

RUNTIME_IN = "# comment\nfastapi==0.143.0\nuvicorn[standard]==0.30.1\nPillow==12.3.0\n"
DEV_IN = "-r requirements.in\n-c requirements.txt\npytest>=8.0\n"


def lock(*packages: tuple[str, str], hashed: bool = True) -> str:
    out = ["#", "# This file is autogenerated by pip-compile", "#"]
    for name, version in packages:
        out.append(f"{name}=={version} \\")
        if hashed:
            out.append("    --hash=sha256:aaaa \\")
            out.append("    --hash=sha256:bbbb")
        out.append("    # via -r requirements.in")
    return "\n".join(out) + "\n"


RUNTIME = [("fastapi", "0.143.0"), ("uvicorn", "0.30.1"), ("pillow", "12.3.0"), ("pydantic", "2.14.1")]


def write(tmp: Path, runtime_in=RUNTIME_IN, dev_in=DEV_IN, runtime=None, dev=None) -> Path:
    (tmp / "requirements.in").write_text(runtime_in)
    (tmp / "requirements-dev.in").write_text(dev_in)
    (tmp / "requirements.txt").write_text(runtime if runtime is not None else lock(*RUNTIME))
    (tmp / "requirements-dev.txt").write_text(dev if dev is not None else lock(*RUNTIME, ("pytest", "9.0.0")))
    return tmp


def test_a_consistent_set_passes(tmp_path):
    assert check(write(tmp_path)) == []


def test_a_bumped_pin_without_a_recompile_fails(tmp_path):
    errors = check(write(tmp_path, runtime_in=RUNTIME_IN.replace("0.143.0", "0.144.0")))
    assert any("fastapi" in e and "recompile" in e for e in errors)


def test_a_new_direct_dependency_without_a_recompile_fails(tmp_path):
    errors = check(write(tmp_path, runtime_in=RUNTIME_IN + "lxml==6.1.3\n"))
    assert any("lxml is missing" in e for e in errors)


def test_an_unpinned_runtime_dependency_fails(tmp_path):
    errors = check(write(tmp_path, runtime_in=RUNTIME_IN + "pydantic>=2\n"))
    assert any("pinned with ==" in e for e in errors)


def test_the_dev_lock_must_match_production_versions(tmp_path):
    dev = lock(("fastapi", "0.143.0"), ("uvicorn", "0.30.1"), ("pillow", "12.3.0"), ("pydantic", "2.99.0"), ("pytest", "9.0.0"))
    errors = check(write(tmp_path, dev=dev))
    assert any("pydantic differs" in e for e in errors)


def test_a_missing_test_tool_fails(tmp_path):
    errors = check(write(tmp_path, dev=lock(*RUNTIME)))
    assert any("pytest is missing" in e for e in errors)


def test_a_lock_without_hashes_fails(tmp_path):
    errors = check(write(tmp_path, runtime=lock(*RUNTIME, hashed=False)))
    assert any("no --hash" in e for e in errors)


@pytest.mark.parametrize("name", ["Pillow", "pillow", "PILLOW"])
def test_names_compare_as_pip_compares_them(tmp_path, name):
    assert check(write(tmp_path, runtime_in=RUNTIME_IN.replace("Pillow", name))) == []


def test_the_real_backend_locks_pass():
    backend = Path(__file__).resolve().parent.parent / "backend"
    assert check(backend) == []
    assert len(read_lock((backend / "requirements.txt").read_text(encoding="utf-8"))) > 10
